def t_endpoints(E):
    T = 'endpoints'
    rows = [('q8', 'Qwen8', 'C|Z', '1{,}000', 'L'), ('q32a', 'Qwen32', 'C|Z', '1{,}000', 'L'),
            ('q32a', 'Qwen32', 'Z|C', '1{,}000', 'L'), ('g468', 'Granite', 'Z|C', '468', 'L'),
            ('g531', 'Granite', 'Z|C', '531', 'F'), ('g999', 'Granite', 'Z|C', '999', 'F'),
            ('ds', 'DeepStack', 'C|Z', '1{,}000', 'L'), ('ds', 'DeepStack', 'Z|C', '1{,}000', 'L')]
    body = []
    for cell, model, c, n, st in rows:
        key = f'end/{cell}/{c}'
        e = E[key]
        kept = 'main' if c == 'C|Z' else 'later'
        rowid = f'{model} {kept} {cell}'
        f = val_cell(T, rowid, 'f', e['f'], src_of(key, E), scale=1.0)
        ratio = '$' + str((Decimal(repr(e['loss_over_JZ']))).quantize(Decimal('0.001'), ROUND_HALF_UP)) + '$'
        record(T, rowid, 'loss_over_gain', ratio, e['loss_over_JZ'], src_of(key, E), 'ratio (3 decimals)')
        out = {'holds': 'holds', 'refuted': 'fails', 'undetermined': 'undetermined'}[e['label']]
        body.append(f'{model} & {kept} & {n} & {f} & {ratio} & {ci_cell(T, rowid, "margin", E, key, field="margin")} '
                    f'& {out} & {st} \\\\')
    cap = ('\\textbf{Single-entry predictions fixed in the protocol: five of six hold.} Each prediction states that '
           'keeping one entry (the other replaced by zeros) loses at most a fraction $f$ of the full visual gain, the '
           'accuracy of the full input minus that with both entries zeroed. Loss/gain is the observed loss as a fraction '
           'of that gain. The margin, in percentage points, is $f$ times the gain minus the loss; a prediction holds when '
           'the whole interval lies above zero. Granite\'s prediction fails on its first 468 images, '
           'on the 531 held-out images and on both together. The four predictions without data (Qwen8 on GQA '
           'spatial and on DocVQA, main kept, $f=0.25$; DeepStack on GQA spatial, each entry kept, $f=0.5$) belong to '
           'cells that were not run. ' + REF)
    head = 'Model & Entry kept & Images & $f$ & Loss/gain & Margin & Outcome & Status \\\\'
    return table_env(T, cap, 'tab:coding_endpoints', '@{}llrcccll@{}', [head], body)


