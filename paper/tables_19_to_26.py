# ---------------------------------------------------------------------------------------------- formatting
def dec(x, scale):
    return (Decimal(repr(float(x)))*Decimal(repr(scale))).quantize(Decimal('0.01'), ROUND_HALF_UP)


def num(x, scale=100.0):
    d = dec(x, scale)
    if d == 0:
        d = abs(d)
    return f'{d:,}'.replace(',', '{,}')


def kb(x):
    return num(x, 1e-3)


def record(table, row, col, printed, raw, source, kind):
    VALUES.append(dict(table=table, row=row, column=col, printed=printed, raw=raw, kind=kind, source=source))


def src_of(key, E):
    return key


def ci_cell(table, row, col, E, key, field='est', scale=100.0, status=None):
    e = E[key]
    v = e[field] if field != 'margin' else e['margin']
    s = f'${num(v, scale)}$ $[{num(e["lo"], scale)}, {num(e["hi"], scale)}]$'
    record(table, row, col, s, dict(value=v, lo=e['lo'], hi=e['hi'], scale=scale), src_of(key, E), 'estimate_ci')
    return s + (f' {status}' if status else '')


def val_cell(table, row, col, x, source, scale=100.0, kind='value'):
    s = f'${num(x, scale)}$'
    record(table, row, col, s, x, source, kind)
    return s


def kb_cell(table, row, col, x, source):
    s = f'${kb(x)}$'
    record(table, row, col, s, x, source, 'KB per unit')
    return s


def cfg_tex(c):
    """main | later notation of the appendix."""
    m, l = c.split('|')

    def side(x, later):
        if x in ('C', 'Z', 'M'):
            return f'\\mathrm{{{x}}}'
        if x.startswith('q'):
            v = int(x[1:])
            return f'{{{v}}}' if later and v < 0 else str(v)
        k = int(x[1:])
        return '\\mathrm{n}' if k == 0 else f'\\mathrm{{n}}{{{"+" if k > 0 else "-"}}}{abs(k)}'
    return f'${side(m, False)}\\,|\\,{side(l, True)}$'


def table_env(name, caption, label, colspec, header, body, wide=True, tabcolsep='4pt', note=None):
    env = 'table*' if wide else 'table'
    out = [GEN, f'\\begin{{{env}}}[t]', '\\centering\\footnotesize', f'\\setlength{{\\tabcolsep}}{{{tabcolsep}}}',
           '\\renewcommand{\\arraystretch}{1.04}', f'\\caption{{{caption}}}', f'\\label{{{label}}}',
           f'\\begin{{tabular}}{{{colspec}}}', '\\toprule']
    for h in header:
        out += ['\\rowcolor{DSTableHeader}', h]
    out += (['\\midrule'] if header else []) + body + ['\\bottomrule', '\\end{tabular}']
    if note:
        out.append(note)
    out.append(f'\\end{{{env}}}')
    return '\n'.join(out) + '\n'


def block(title, n):
    return f'\\rowcolor{{DSTableAccent}}\\multicolumn{{{n}}}{{@{{}}l}}{{\\textbf{{{title}}}}}\\\\'


def nfmt(n):
    return f'{n:,}'.replace(',', '{,}')


