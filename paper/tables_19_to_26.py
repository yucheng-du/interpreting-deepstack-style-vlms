def t_role(E):
    T = 'role'
    rows = [('q8', 'Qwen8, attribute', 'high', 'q2|k+4', 'q10|k-4'), ('q8', 'Qwen8, attribute', 'low', 'q6|k+4', 'q10|k-2'),
            ('q32d', 'Qwen32, DocVQA', 'high', 'q8|k+4', 'q12|k-2'), ('q32d', 'Qwen32, DocVQA', 'low', 'q12|k+2', 'q16|k-4'),
            ('g468', 'Granite, attribute (468)', 'high', 'q8|k-4', 'q0|k+2'),
            ('g468', 'Granite, attribute (468)', 'low', 'q12|k-4', 'q8|k+2')]
    body = []
    for cell, name, bud, a, b in rows:
        key = f'diff/{cell}/{a}/{b}'
        e = E[key]
        rid = f'{cell} {bud}'
        out = {'holds': 'holds', 'refuted': 'fails', 'undetermined': 'undetermined'}[
            'holds' if e['lo'] > 0 else 'refuted' if e['hi'] < 0 else 'undetermined']
        body.append(f'{name} & {bud} & {cfg_tex(a)} & {kb_cell(T, rid, "KB role", e["a_score"]["bytes"], src_of(key, E))} & '
                    f'{val_cell(T, rid, "score role", e["a_score"]["est"], src_of(key, E))} & {cfg_tex(b)} & '
                    f'{kb_cell(T, rid, "KB mirror", e["b_score"]["bytes"], src_of(key, E))} & '
                    f'{val_cell(T, rid, "score mirror", e["b_score"]["est"], src_of(key, E))} & '
                    f'{ci_cell(T, rid, "difference", E, key)} & {out} \\\\')
    cap = ('\\textbf{Role-direction predictions fixed in the protocol: they hold for Qwen and fail for Granite.} For a '
           'model whose main entry carried most of the accuracy (Qwen8 attribute, Qwen32 DocVQA) the role allocation codes '
           'the later entries coarser than scale-normalized (n+$k$); for Granite, whose later entries carried most of it, '
           'it codes them finer (n$-k$). The mirror reverses the sign of $k$. At each budget each allocation takes its '
           'best configuration on calibration images within the byte cap, so the two compared configurations need not '
           'have equal bytes. The high and low budgets are the cheapest shared-QP configurations reaching 95\\% and 60\\% '
           'of the gap between both entries zeroed and the full input on calibration images. The prediction was role '
           'minus mirror above zero. Granite has only its first 468 images, so the protocol\'s analysis was not run for it; its differences are computed with the same '
           'bootstrap as the other rows. Score in percent '
           '(ANLS$\\times$100 for DocVQA), KB per image or document, difference in points. All rows are L. Notation as in '
           'Table~\\ref{tab:coding_deepstack}. ' + REF)
    head = 'Model, task & Budget & Role & KB & Score & Mirror & KB & Score & Difference & Outcome \\\\'
    return table_env(T, cap, 'tab:coding_role', '@{}llcrrcrrcl@{}', [head], body, tabcolsep='3.2pt')


