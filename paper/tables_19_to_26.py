def t_corners(E):
    T = 'corners'
    panels = [[('q8', 'Qwen8'), ('q32a', 'Qwen32'), ('g999', 'Granite, 999'), ('ds', 'DeepStack')],
              [('g531', 'Granite, 531'), ('g468', 'Granite, 468'), ('q32d', 'Qwen32 DocVQA'), (None, '')]]
    body = []
    for pi, panel in enumerate(panels):
        if pi:
            body.append('\\midrule')
        heads = ' & '.join(h for _, h in panel)
        body += ['\\rowcolor{DSTableHeader}', f'Main input & Later input & {heads} \\\\']
        ns = []
        for cell, _ in panel:
            if cell is None:
                ns.append('')
                continue
            e = E[f'score/{cell}/C|C']
            ns.append(f'{nfmt(e["n_units"])} / {nfmt(e["n_questions"])}')
            record(T, 'n', cell, ns[-1], [e['n_units'], e['n_questions']], src_of(f'score/{cell}/C|C', E), 'count')
        body.append(f'\\multicolumn{{2}}{{@{{}}l}}{{\\textit{{Images or documents / questions}}}} & '
                    + ' & '.join(ns) + ' \\\\')
        for c in SINGLE:
            m, l = c.split('|')
            cells = []
            for cell, _ in panel:
                if cell is None:
                    cells.append('')
                else:
                    cells.append(ci_cell(T, c, cell, E, f'score/{cell}/{c}'))
            body.append(f'{WORD[m]} & {WORD[l]} & ' + ' & '.join(cells) + ' \\\\')
    cap = ('\\textbf{Which entry suffices depends on the model and the replacement.} GQA attribute accuracy on new images '
           'when an entry\'s features are replaced; Qwen32 '
           'DocVQA reports ANLS$\\times$100 on all 474 remaining DocVQA documents. ``image\'\' keeps the entry\'s features unchanged; '
           '``zeros\'\' sets all of them to zero; ``mean\'\' sets every position to the entry\'s mean feature vector over '
           '48 calibration images (for DocVQA, the 56 page images of 48 calibration documents), so neither replacement '
           'depends on the test image. Qwen8, Qwen32 and DeepStack are evaluated '
           'on the 1,000 confirmation images. Granite\'s first 468 images come from the confirmation runs; its seven '
           'configurations were then run on the 531 remaining images, which Granite had not seen, and 999 pools the two. '
           'Values in percent. ' + BOOT)
    return table_env(T, cap, 'tab:coding_corners', '@{}llcccc@{}', [body[1]], body[2:])


