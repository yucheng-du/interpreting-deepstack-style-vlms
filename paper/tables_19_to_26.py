def t_qwen(E):
    """Rows are the seven main-only points and the scale-normalized points inside the
    shared byte range; each row is compared with the shared-QP curve at the same bytes (P), and the main-only rows
    also with the shared configuration at the same main QP (F). The shared-QP points are not tabulated."""
    T = 'qwen'
    body = []
    for cell, title in QCELLS:
        body.append(block(title, 8))
        for fam in ('main_only', 'scale_normalized'):
            ks = sorted([k for k in E if k.startswith(f'match/{cell}/') and family(k.split('/', 2)[2]) == fam],
                        key=lambda k: sort_cfg(k.split('/', 2)[2]))
            for mkey in ks:
                m = E[mkey]
                if not m['inside']:
                    continue
                c = m['config']
                rid = f'{cell} {c}'
                skey = f'score/{cell}/{c}'
                assert abs(E[skey]['est'] - m['score']) < 1e-12 and abs(E[skey]['bytes'] - m['bytes']) < 1e-9
                if fam == 'main_only':
                    q = c.split('|')[0]
                    dkey = f'diff/{cell}/{c}/{q}|{q}'
                    d = E[dkey]
                    same = (f'{ci_cell(T, rid, "difference, same main QP", E, dkey)} & '
                            f'{val_cell(T, rid, "byte change %, same main QP", d["bytes_change_pct"], src_of(dkey, E), scale=1.0)}')
                    lab = 'main only'
                else:
                    same = ' & '
                    lab = 'scale-normalized'
                body.append(f'{cfg_tex(c)} & {lab} & {kb_cell(T, rid, "KB", m["bytes"], src_of(skey, E))} & '
                            f'{ci_cell(T, rid, "score", E, skey)} & {same} & '
                            f'{val_cell(T, rid, "shared curve at same KB", m["curve_score"], src_of(mkey, E))} & '
                            f'{ci_cell(T, rid, "difference, shared curve", E, mkey)} \\\\')
    out = [f"{k.split('/')[1]} {k.split('/', 2)[2]}" for k in E
           if k.startswith('match/q') and not E[k]['inside']]
    ins = [E[k] for k in E if k.startswith('match/q') and E[k]['inside']]
    mo = [e for e in ins if family(e['config']) == 'main_only']
    sn = [e for e in ins if family(e['config']) == 'scale_normalized']
    cnt = lambda es: (sum(e['lo'] <= 0 <= e['hi'] for e in es), sum(e['lo'] > 0 for e in es), sum(e['hi'] < 0 for e in es))
    mo_c, sn_c = cnt(mo), cnt(sn)
    above = [e for e in mo if e['lo'] > 0]
    below = [e for e in mo if e['hi'] < 0]
    assert len(mo) == 7 and len(sn) == 13 and len(out) == 5 and mo_c == (5, 1, 1) and sn_c[1:] == (0, 8), \
        (len(mo), len(sn), len(out), mo_c, sn_c)
    assert above[0]['cell'] == 'q32a' and below[0]['cell'] == 'q32d'
    words = {0: 'None', 8: 'eight', 5: 'five', 1: 'one'}
    a = above[0]
    lo_c, hi_c = a['bracket']
    sa, sb = E[f'score/q32a/{lo_c}'], E[f'score/q32a/{hi_c}']
    record(T, 'caption', 'bracket KB/score', [kb(sa['bytes']), num(sa['est']), kb(sb['bytes']), num(sb['est'])],
           [sa['bytes'], sa['est'], sb['bytes'], sb['est']], src_of(f'score/q32a/{lo_c}', E), 'caption values')
    # the two further Qwen8 comparisons, in the caption
    extra = []
    for a_, b_, st in (('q0|Z', 'q2|q2', 'F'), ('q2|k+4', 'q2|q2', 'L')):
        dkey = f'diff/q8/{a_}/{b_}'
        d = E[dkey]
        rid = f'q8 {a_} vs {b_}'
        ci = ci_cell(T, rid, 'difference', E, dkey)
        bc = d['bytes_change_pct']
        bcs = val_cell(T, rid, 'byte change %', abs(bc), src_of(dkey, E), scale=1.0)
        extra.append((a_, b_, st, ci, bcs, 'more' if bc > 0 else 'fewer', d))
    (a0, b0, st0, ci0, bc0, mf0, _), (a1, b1, st1, ci1, bc1, mf1, d1) = extra
    sel = d1['a_score']
    selkb = kb_cell(T, 'q8 q2|k+4 vs q2|q2', 'KB', sel['bytes'], src_of('diff/q8/q2|k+4/q2|q2', E))
