#!/usr/bin/env python3
"""Typeset post hoc four-cell diagnostics for Appendix G from the audit analysis outputs.

Inputs are written by scripts/audit_v15/four_cell_posthoc.py and docvqa_format_sensitivity.py,
which stream archived v15 observations without inference. Values are only formatted here.
"""
import hashlib
import json
from pathlib import Path

from analysis.paths import INPUT, OUT as RENDERED, output_dir
FINAL = INPUT/'posthoc'
FOUR, FORMAT = FINAL/'four_cell_posthoc.json', FINAL/'docvqa_format_sensitivity.json'
OUTPUT = RENDERED/'posthoc_tables.tex'
ROWS = [('qwen32b_stripe_identity', 'Qwen32', 'Stripes 0.43, identity'),
        ('qwen32b_text_identity', 'Qwen32', 'Text 2.5, identity'),
        ('qwen32b_stripe_direct', 'Qwen32', 'Stripes 0.43, direct'),
        ('qwen8b_stripe_direct', 'Qwen8', 'Stripes 0.43, direct'),
        ('qwen32b_text_direct', 'Qwen32', 'Text 2.5, direct'),
        ('qwen32b_color_direct', 'Qwen32', 'Color 0.05, direct'),
        ('deepstack7b_color_direct', 'DeepStack', 'Color 0.05, direct'),
        ('ibm4b_position_direct', 'Granite', 'Position 0.3, direct'),
        ('ibm4b_text_direct', 'Granite', 'Text 2.5, direct'),
        ('ibm4b_gqa_attribute', 'Granite', 'GQA attr.\\ 5 px, C+P'),
        ('deepstack7b_gqa_attribute', 'DeepStack', 'GQA attr.\\ 5 px, C+P'),
        ('qwen8b_docvqa', 'Qwen8', 'DocVQA 180 px, ANLS'),
        ('qwen32b_docvqa', 'Qwen32', 'DocVQA 180 px, ANLS'),
        ('ibm4b_docvqa', 'Granite', 'DocVQA 180 px, ANLS'),
        ('deepstack7b_docvqa', 'DeepStack', 'DocVQA 180 px, ANLS')]
CONTRASTS = [('qwen32b_stripe_identity - qwen32b_text_identity', 'Qwen32 stripes minus text, identity'),
             ('qwen32b_stripe_direct - qwen32b_text_direct', 'Qwen32 stripes minus text, direct'),
             ('qwen32b_stripe_direct - qwen8b_stripe_direct', 'Qwen32 minus Qwen8 stripes, direct'),
             ('qwen32b_docvqa - qwen8b_docvqa', 'Qwen32 minus Qwen8 DocVQA 180 px')]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def cell(stat, interval=True):
    mean = f"${stat['mean']:.3f}$"
    if not interval:
        return mean
    if stat['ci_low'] is None:
        # Zero standard error: a zero-width interval, the notation of the main text.
        z = f"{stat['mean'] + 0.0:.3f}"
        return mean+f" $[{z}, {z}]$"
    return mean+f" $[{stat['ci_low']:.3f}, {stat['ci_high']:.3f}]$"


def main():
    four, fmt = json.loads(FOUR.read_text()), json.loads(FORMAT.read_text())
    lines = ['% Generated by v15_revision/build_posthoc_table.py; post hoc values, do not edit.',
             '\\begin{table*}[t]', '\\centering\\footnotesize', '\\setlength{\\tabcolsep}{3pt}',
             '\\renewcommand{\\arraystretch}{1.04}',
             '\\caption{\\textbf{Single-entry losses separate main-limited, later-limited and either-sufficient cells.} '
             'Post hoc single-entry losses and item changes for selected cells of the calibrated experiment, recomputed '
             'from the stored model outputs without new inference. $U_M=A_{CC}-A_{DC}$ and $U_L=A_{CC}-A_{CD}$ carry paired '
             'intervals over templates (Student-$t$) or images and documents (normal); $\\Lambda=G_D+U_M$. '
             'Changes count items whose score rises or falls from DD to DC: the 64 distinct template--object items for '
             'synthetic cells (duplicated recovery rows were checked to be identical) and all questions for benchmarks. '
             'C+P: case-and-punctuation matching.}',
             '\\label{tab:v15_posthoc}', '\\begin{tabular}{@{}llcccl@{}}', '\\toprule', '\\rowcolor{DSTableHeader}',
             'Model & Cell & $\\Lambda$ & $U_M$ & $U_L$ & Changes \\\\', '\\midrule']
    for key, model, label in ROWS:
        e = four['cases'][key]
        if 'transitions_distinct_items' in e:
            tr = e['transitions_distinct_items']
            change = f"{tr['w2r']} up, {tr['r2w']} down of {tr['n_items']}"
        else:
            q = e['question_changes_dd_to_dc']
            change = f"{q['improved']} up, {q['worsened']} down of {q['n_questions']}"
        lines.append(f"{model} & {label} & {cell(e['Lambda'], False)} & {cell(e['U_M'])} & {cell(e['U_L'])} & {change} \\\\")
    lines += ['\\bottomrule', '\\end{tabular}', '\\end{table*}', '']
    lines += ['\\begin{table*}[t]', '\\centering\\footnotesize', '\\setlength{\\tabcolsep}{4pt}',
              '\\renewcommand{\\arraystretch}{1.04}',
              '\\caption{\\textbf{At similar loss, Qwen32 recovers more on stripes than on text, and more than Qwen8 on stripes.} '
              'Post hoc paired contrasts and the Granite DocVQA format check. Contrasts subtract within shared '
              'templates or documents before the interval is computed. The format check rescores the stored 180-pixel '
              "answers with the experiment's scorer: each row removes one kind of final mark before exact matching, C+P applies all "
              "three, and the "
              'last row gives the share of answers ending in a period.}',
              '\\label{tab:v15_posthoc_contrasts}', '\\begin{tabular}{@{}lcc@{}}', '\\toprule', '\\rowcolor{DSTableHeader}',
              'Paired contrast & $G_D$ difference & $\\Lambda$ difference \\\\', '\\midrule']
    for key, label in CONTRASTS:
        e = four['contrasts'][key]
        lines.append(f"{label} & {cell(e['G_D'])} & {cell(e['Lambda'])} \\\\")
    lines += ['\\midrule', '\\rowcolor{DSTableHeader}', 'Granite DocVQA, 180 px & CC / CD / DC / DD & $I_{\\rm rec}$ \\\\', '\\midrule']
    g = fmt['ibm4b']['lowres-long180']
    for rule, label in (('anls_organizer', 'Organizer ANLS'), ('exact_lower_strip', 'Lowercase exact'),
                        ('exact_period_only', 'Exact, final period removed'), ('exact_other_marks_only', 'Exact, final ! or ? removed'),
                        ('exact_quotes_only', 'Exact, outer quotes removed'), ('exact_case_punct', 'C+P exact (all three)'),
                        ('trailing_period', 'Ends with a period')):
        cells = ' / '.join(f"{g[rule][c]['mean']:.3f}" for c in ('CC', 'CD', 'DC', 'DD'))
        lines.append(f"{label} & ${cells}$ & {cell(g[rule]['I_rec'])} \\\\")
    lines += ['\\bottomrule', '\\end{tabular}', '\\end{table*}']
    OUTPUT.write_text('\n'.join(lines)+'\n')
    (OUTPUT.parent/'posthoc_table_manifest.json').write_text(json.dumps(
        {'generator': str(Path(__file__).resolve()), 'generator_sha256': sha(Path(__file__)),
         'inputs': {str(FOUR): sha(FOUR), str(FORMAT): sha(FORMAT)}, 'output': str(OUTPUT), 'output_sha256': sha(OUTPUT)},
        indent=1)+'\n')
    print('wrote', OUTPUT)


if __name__ == '__main__':
    output_dir()
    main()
